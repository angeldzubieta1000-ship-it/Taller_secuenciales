#Funciones matematicas

import math


numero = float(input("Ingrese un numero: "))

print ("El valor de seno es: ", math.sin(numero))
print ("El valor de coseno es: ", math.cos(numero))
print ("El valor de tangente es: ", math.tan(numero))
print ("El valor de raiz es: ", math.sqrt(numero))
print ("El valor de logaritmo Natural es: ", math.log(numero))
print ("El valor de logaritmo base 10 es: ", math.log10(numero))